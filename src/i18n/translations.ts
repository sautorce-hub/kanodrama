type DeepPartial<T> = {
  [K in keyof T]?: T[K] extends Array<infer U>
    ? Array<U>
    : T[K] extends object
    ? DeepPartial<T[K]>
    : T[K];
};

function mergeTranslationObjects<T extends Record<string, unknown>>(
  base: T,
  patch: DeepPartial<T>
): T {
  const result = { ...base } as Record<string, unknown>;
  for (const key of Object.keys(patch)) {
    const patchVal = (patch as Record<string, unknown>)[key];
    if (patchVal === undefined) continue;
    const baseVal = result[key];
    if (
      patchVal &&
      typeof patchVal === 'object' &&
      !Array.isArray(patchVal) &&
      baseVal &&
      typeof baseVal === 'object' &&
      !Array.isArray(baseVal)
    ) {
      result[key] = mergeTranslationObjects(
        baseVal as Record<string, unknown>,
        patchVal as DeepPartial<Record<string, unknown>>
      );
    } else {
      result[key] = patchVal;
    }
  }
  return result as T;
}

function createLocalizedTranslation(patch: DeepPartial<Translations>): Translations {
  return mergeTranslationObjects(
    EN_TRANSLATIONS as unknown as Record<string, unknown>,
    patch as DeepPartial<Record<string, unknown>>
  ) as unknown as Translations;
}

